export function resolveRpgClassLabel(options: {
  kind: WalkStarKind | string;
  alameda?: WalkAlameda | string;
  isDeceased?: boolean;
  isNewEraVisionary?: boolean;
  dominantGenre?: string | null;
  fallbackTitle?: string | null;
}): string {
  if (options.isDeceased) return 'Guardião Eterno';
  if (options.kind === 'director') {
    if (options.isNewEraVisionary) return 'Visionário da Nova Era';
    if (options.dominantGenre && DIRECTOR_CLASS_BY_GENRE[options.dominantGenre]) {
      return DIRECTOR_CLASS_BY_GENRE[options.dominantGenre];
    }
    return options.fallbackTitle || 'Autor Cinematográfico';
  }
  if (options.kind === 'dublador') return 'Mestre das Vozes';
  if (options.alameda === 'casais') {
    if (options.dominantGenre && COUPLE_CLASS_BY_GENRE[options.dominantGenre]) {
      return COUPLE_CLASS_BY_GENRE[options.dominantGenre];
    }
    return 'Química de Milhões';
  }
  if (options.kind === 'group') return 'Aliança do Elenco';
  if (options.dominantGenre && GENRE_CLASS_BY_NAME[options.dominantGenre]) {
    return GENRE_CLASS_BY_NAME[options.dominantGenre];
  }
  return options.fallbackTitle || 'Lenda do Cinema';
}

