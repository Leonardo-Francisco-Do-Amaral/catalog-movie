export const UNIVERSE_CHECKPOINT_XP = 30;
export const UNIVERSE_MEGA_BASE_XP = 500;
export const UNIVERSE_MEGA_XP_PER_MOVIE = 25;

export function computeMegaSagaCompletionXp(totalMoviesCount: number): number {
  const safeMovies = Math.max(0, Math.floor(Number(totalMoviesCount) || 0));
  return UNIVERSE_MEGA_BASE_XP + safeMovies * UNIVERSE_MEGA_XP_PER_MOVIE;
}

